/*
 * chat_tool_calls_test: the tolerant reading of tool calls (chat_completions.c, chat_completions.h's Calls) against
 * its grammar's model, tools/models/deepseek_v41_flash/tool_calls/dsml_model.py.
 *
 *     chat_tool_calls_test [<corpus file>]
 *
 * Without an argument, as `make check` runs every test: the captured regressions, kept for good. A call seen in
 * serving on 20 Nov 2026 whose name lost its closing quote, as pasted (line feeds shown as spaces) and with line
 * feeds (one call j, its three parameters, never guessed to a declared tool), and its well-formed reconstruction,
 * each in six contexts (two line feeds, one, none, after text with two, a space, one), with thinking off and on; a
 * list_agents call with a blank line and no closing (26 Oct 2026); a block straight after the content (the
 * encoder's template discussion 39, 30 Oct 2026); the blocks v0.0.5-alpha gave out as text; the design's decided
 * cases. Each is fed whole, at every split in two, one byte at a time and in pieces of 1 to 6 bytes (fixed and
 * cycling: the speculative verify widths), whole and streamed, and must give the same content, reasoning, calls and
 * finish every time, byte for byte (G2), with no marker in the text (G1); Messages and Responses must give one
 * answer for every feeding and the same calls. --dsml_parsing=reference keeps v0.0.5-alpha's text. With a corpus
 * file (tools/models/deepseek_v41_flash/tool_calls/dsml_corpus.py writes it: the grammar's variants, or random
 * mutations of them), each case is fed every way above and must give the model's content, reasoning, calls, finish
 * reason and repair counts.
 */
