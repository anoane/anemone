#define WIDE_BAR "\xEF\xBD\x9C" /* U+FF5C */
#define MARKER_SPACE_BYTES " \t\r\n"
#define DSML           \
	"\xEF\xBD\x9C" \
	"DSML"         \
	"\xEF\xBD\x9C"
#define MODEL "test-model"
#define IDENTIFIER "chatcmpl-1"
#define CREATED 1700000000
#define PROMPT_TOKENS 3u
#define TEXT_CAPACITY 1048576u
#define BODY_CAPACITY 65536u
#define SCRATCH_CAPACITY 1048576u
#define LARGEST_PIECE 6u /* the speculative draft's widest verify burst */
#define HEX_BASE 16
#define GROWTH 2u
#define HEX_DIGITS_PER_BYTE 2u
#define DECIMAL_BASE 10
#define UNICODE_ESCAPE_DIGITS 4u /* \uXXXX; json_write_string's are \u00XX */
#define CALL_JOIN_BYTES 2u /* "," between calls, the "{" a delta's call lost */
#define FEEDINGS_DEFERRED \
	2u /* every second feeding defers a stop's finish, as speculative serving does */
#define EVERY_SPLIT_MOST_BYTES \
	4096u /* a longer corpus case is split everywhere for Chat alone */
#define MESSAGES_NAME_MOST 64u
#define MESSAGES_NAME_BYTES \
	"abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-"
#define THINKING_EFFORT "high"

/* How the bytes of a case are fed: whole, split in two at split, in pieces of piece bytes, or cycling 1..6. */
enum feeding { FEED_WHOLE, FEED_SPLIT, FEED_FIXED, FEED_CYCLING };
enum api { API_CHAT, API_MESSAGES, API_RESPONSES, API_COUNT };

struct text {
	char *bytes;
	size_t count, capacity;
};

/* A case: the request's settings, the generated bytes, and (from a corpus) what the model says it gives. */
struct calls_case {
	char name[BODY_CAPACITY];
	struct text stream, tools, stops, content, reasoning, calls;
	bool has_tools, is_thinking, is_reference, is_limited, has_expectation;
	uint32_t thinking_budget; /* reasoning that ends by its token only (Messages' budgets) */
	char finish[CHAT_IDENTIFIER_CAPACITY];
	uint32_t repairs[CHAT_CALLS_REPAIR_KINDS];
};

/* What one feeding gave. */
struct observed {
	struct text content, reasoning, calls, output;
	char finish[CHAT_IDENTIFIER_CAPACITY];
	uint32_t call_count, repairs[CHAT_CALLS_REPAIR_KINDS];
	bool is_short, is_failed;
};

static int failures;
static uint64_t runs;
static const char *context = "";

static void expect(bool condition, const char *what)
{
	if (!condition) {
		(void)printf("FAILED: %s: %s\n", context, what);
		failures++;
	}
}

/* Appends count bytes, NUL-ended; on a refused allocation the text is left as it was and the run fails. */
static void text_appended(struct text *text, const char *bytes, size_t count)
{
	if (text->count + count + 1u > text->capacity) {
		size_t capacity = text->capacity != 0 ? text->capacity :
							BODY_CAPACITY;
		while (capacity < text->count + count + 1u) {
			capacity *= GROWTH;
		}
		char *const grown = realloc(text->bytes, capacity);
		if (grown == NULL) {
			expect(false, "memory for the test's texts");
			return;
		}
		text->bytes = grown;
		text->capacity = capacity;
	}
	if (count != 0) {
		memcpy(text->bytes + text->count, bytes, count);
	}
	text->count += count;
	text->bytes[text->count] = '\0';
}

static void text_set(struct text *text, const char *bytes, size_t count)
{
	text->count = 0;
	text_appended(text, bytes, count);
}

static bool texts_equal(const struct text *first, const struct text *second)
{
	return first->count == second->count &&
	       (first->count == 0 ||
		memcmp(first->bytes, second->bytes, first->count) == 0);
}

static void observed_free(struct observed *observed)
{
	free(observed->content.bytes);
	free(observed->reasoning.bytes);
	free(observed->calls.bytes);
	free(observed->output.bytes);
	*observed = (struct observed){ 0 };
}

/* A JSON string of a request body. */
static size_t json_appended(char *body, size_t length, const char *bytes,
			    size_t count)
{
	struct json_writer writer = { body + length, BODY_CAPACITY - length,
				      0 };
	json_write_string(&writer, (struct json_bytes){ bytes, count });
	return writer.length <= writer.capacity ? length + writer.length :
						  BODY_CAPACITY;
}

static size_t appended(char *body, size_t length, const char *text)
{
	const int written = length < BODY_CAPACITY ?
				    snprintf(body + length,
					     BODY_CAPACITY - length, "%s",
					     text) :
				    -1;
	return written >= 0 && length + (size_t)written < BODY_CAPACITY ?
		       length + (size_t)written :
		       BODY_CAPACITY;
}

/* The request a case asks for, read as the server reads one: its tools by name (their names kept in names as the
 * server keeps them for the answer), its stops, thinking on or off. A list is the bytes of each item, each ended by
 * a NUL. */
static bool request_read(const struct calls_case *calls_case, uint32_t api,
			 bool is_streamed, struct chat_request *request,
			 struct chat_buffer *names)
{
	static char body[BODY_CAPACITY];
	size_t length = appended(
		body, 0,
		"{\"messages\":[{\"role\":\"user\",\"content\":\"x\"}],\"reasoning_effort\":\"");
	length = appended(body, length,
			  calls_case->is_thinking ? THINKING_EFFORT : "none");
	length = appended(body, length, "\"");
	for (size_t at = 0, index = 0;
	     calls_case->has_tools && at < calls_case->tools.count; index++) {
		const size_t count = strlen(calls_case->tools.bytes + at);
		length = appended(body, length,
				  index == 0 ? ",\"tools\":[" : ",");
		length = appended(
			body, length,
			"{\"type\":\"function\",\"function\":{\"name\":");
		length = json_appended(body, length,
				       calls_case->tools.bytes + at, count);
		length = appended(body, length, "}}");
		at += count + 1u;
		length = at >= calls_case->tools.count ?
				 appended(body, length, "]") :
				 length;
	}
	for (size_t at = 0, index = 0; at < calls_case->stops.count; index++) {
		const size_t count = strlen(calls_case->stops.bytes + at);
		length = appended(body, length,
				  index == 0 ? ",\"stop\":[" : ",");
		length = json_appended(body, length,
				       calls_case->stops.bytes + at, count);
		at += count + 1u;
		length = at >= calls_case->stops.count ?
				 appended(body, length, "]") :
				 length;
	}
	length = appended(body, length, "}");
	const struct chat_request defaults = {
		.max_tokens = UINT32_MAX,
		.top_p = 1.0f,
		.is_seeded = true,
		.is_calls_reference = calls_case->is_reference
	};
	struct chat_refusal refusal = { 0 };
	const bool is_read = length < BODY_CAPACITY &&
			     chat_request_read(body, length, MODEL, NULL,
					       &defaults, request,
					       &refusal) == 0;
	request->is_streamed = is_streamed;
	request->includes_usage = true;
	request->thinking_budget = calls_case->thinking_budget;
	request->is_messages = api == API_MESSAGES;
	request->is_responses = api == API_RESPONSES;
	if (is_read) {
		chat_tool_names_kept(body + request->tools_begin,
				     request->tools_end - request->tools_begin,
				     names);
	}
	return is_read;
}

/* The finish reason a Chat answer says. */
static void finish_found(const struct text *output, char *finish)
{
	static const char key[] = "\"finish_reason\":\"";
	const char *at = NULL;
	for (const char *found = output->bytes;
	     found != NULL && output->count != 0;) {
		found = memmem(found,
			       output->count - (size_t)(found - output->bytes),
			       key, strlen(key));
		at = found != NULL ? found + strlen(key) : at;
		found = found != NULL ? found + 1 : NULL;
	}
	const char *const end =
		at != NULL ?
			memchr(at, '"',
			       output->count - (size_t)(at - output->bytes)) :
			NULL;
	const size_t count = end != NULL && (size_t)(end - at) <
						     CHAT_IDENTIFIER_CAPACITY ?
				     (size_t)(end - at) :
				     0;
	memcpy(finish, at != NULL ? at : "", count);
	finish[count] = '\0';
}

/* Appends the JSON string at at (its opening quote) unescaped to text; where it ends. short_escapes pairs each short
 * escape's letter with its byte. */
static const char *string_unescaped(const char *at, const char *end,
				    struct text *text)
{
	static const char short_escapes[] = "n\nt\tr\rb\bf\f";
	for (at++; at < end && *at != '"'; at++) {
		char byte = *at;
		if (byte == '\\' && at + 1 < end) {
			at++;
			const char *const short_escape =
				strchr(short_escapes, *at);
			if (*at == 'u' &&
			    (size_t)(end - at) > UNICODE_ESCAPE_DIGITS) {
				const char digits[] = {
					at[UNICODE_ESCAPE_DIGITS - 1u],
					at[UNICODE_ESCAPE_DIGITS], '\0'
				};
				byte = (char)(unsigned char)strtoul(
					digits, NULL, HEX_BASE);
				at += UNICODE_ESCAPE_DIGITS;
			} else if (short_escape != NULL && *at != '\0') {
				byte = short_escape[1];
			} else {
				byte = *at;
			}
		}
		text_appended(text, &byte, 1);
	}
	return at;
}

/* A stream's content and reasoning deltas joined, and its tool_calls deltas as a whole answer's calls. */
static void stream_read(const struct text *output, struct observed *observed)
{
	static const char content_key[] = "\"delta\":{\"content\":",
			  reasoning_key[] = "\"delta\":{\"reasoning_content\":",
			  call_key[] = "{\"tool_calls\":[{\"index\":",
			  call_end[] = "]},\"finish_reason\"";
	const char *const end = output->bytes + output->count;
	for (const char *at = output->bytes; at != NULL && at < end; at++) {
		const size_t left = (size_t)(end - at);
		if (left > strlen(content_key) &&
		    memcmp(at, content_key, strlen(content_key)) == 0) {
			at = string_unescaped(at + strlen(content_key), end,
					      &observed->content);
		} else if (left > strlen(reasoning_key) &&
			   memcmp(at, reasoning_key, strlen(reasoning_key)) ==
				   0) {
			at = string_unescaped(at + strlen(reasoning_key), end,
					      &observed->reasoning);
		} else if (left > strlen(call_key) &&
			   memcmp(at, call_key, strlen(call_key)) == 0) {
			const char *const object =
				memchr(at + strlen(call_key), ',',
				       left - strlen(call_key));
			const char *const object_end =
				object != NULL ?
					memmem(object, (size_t)(end - object),
					       call_end, strlen(call_end)) :
					NULL;
			if (object_end != NULL) {
				if (observed->calls.count != 0) {
					text_appended(&observed->calls, ",", 1);
				}
				text_appended(&observed->calls, "{", 1);
				text_appended(&observed->calls, object + 1,
					      (size_t)(object_end - object) -
						      1u);
				at = object_end;
			}
		}
	}
}

/* Feeds a case's bytes as feeding says, the end token when it ends with one, and finishes. */
static bool answered(const struct calls_case *calls_case, uint32_t api,
		     bool is_streamed, uint32_t feeding, size_t size,
		     bool defers, struct observed *observed)
{
	static char scratch[SCRATCH_CAPACITY];
	struct chat_request *const request = calloc(1, sizeof(*request));
	struct chat_answer answer = { 0 };
	struct chat_buffer names = { 0 };
	*observed = (struct observed){ 0 };
	if (request == NULL ||
	    !request_read(calls_case, api, is_streamed, request, &names)) {
		chat_buffer_free(&names);
		free(request);
		return false;
	}
	chat_answer_begin(&answer, request, MODEL, IDENTIFIER, CREATED,
			  PROMPT_TOKENS);
	answer.tool_names = &names;
	answer.defers_stop_finish = defers;
	answer.messages.scratch = scratch;
	answer.messages.scratch_capacity = sizeof(scratch);
	for (size_t position = 0, turn = 0; position < calls_case->stream.count;
	     turn++) {
		const size_t left = calls_case->stream.count - position;
		const size_t wanted =
			feeding == FEED_WHOLE ?
				left :
			feeding == FEED_SPLIT ?
				(position < size ? size - position : left) :
			feeding == FEED_FIXED ? size :
						1u + turn % LARGEST_PIECE;
		const size_t piece = wanted < left ? wanted : left;
		(void)chat_answer_token(&answer,
					calls_case->stream.bytes + position,
					(uint32_t)piece);
		position += piece;
	}
	if (!calls_case->is_limited) {
		(void)chat_answer_token(&answer, NULL, 0);
	}
	chat_answer_finish(&answer, calls_case->is_limited ? "length" : "stop");
	runs++;
	text_set(&observed->output,
		 answer.output.bytes != NULL ?
			 answer.output.bytes + answer.output.sent :
			 "",
		 answer.output.bytes != NULL ?
			 answer.output.count - answer.output.sent :
			 0);
	if (api == API_CHAT && !is_streamed) {
		text_set(&observed->content,
			 answer.content.bytes != NULL ? answer.content.bytes :
							"",
			 answer.content.count);
		text_set(&observed->reasoning,
			 answer.reasoning.bytes != NULL ?
				 answer.reasoning.bytes :
				 "",
			 answer.reasoning.count);
		text_set(&observed->calls,
			 answer.calls.bytes != NULL ? answer.calls.bytes : "",
			 answer.calls.count);
	} else if (api == API_CHAT) {
		stream_read(&observed->output, observed);
	}
	if (api == API_CHAT) {
		finish_found(&observed->output, observed->finish);
	}
	observed->call_count = answer.call_count;
	observed->is_failed =
		answer.messages.failed ||
		(observed->output.count != 0 &&
		 strstr(observed->output.bytes, CHAT_ENGINE_FAILED) != NULL);
	observed->is_short = answer.output.is_short;
	chat_answer_repairs(&answer, calls_case->is_limited, observed->repairs);
	chat_answer_free(&answer);
	chat_buffer_free(&names);
	free(request);
	return true;
}

/* Whether two whole Messages or Responses bodies are one answer: the same bytes from the body's start to its usage,
 * whose token counts (and so the head's length) follow how many pieces came. */
static bool bodies_equal(const struct text *first, const struct text *second)
{
	static const char body_start[] = "\r\n\r\n", usage[] = "\"usage\":";
	const char *const ends[] = {
		first->count != 0 ? memmem(first->bytes, first->count, usage,
					   strlen(usage)) :
				    NULL,
		second->count != 0 ? memmem(second->bytes, second->count, usage,
					    strlen(usage)) :
				     NULL
	};
	const char *const starts[] = {
		first->count != 0 ? memmem(first->bytes, first->count,
					   body_start, strlen(body_start)) :
				    NULL,
		second->count != 0 ? memmem(second->bytes, second->count,
					    body_start, strlen(body_start)) :
				     NULL
	};
	if (ends[0] == NULL || ends[1] == NULL || starts[0] == NULL ||
	    starts[1] == NULL) {
		return texts_equal(first, second); /* a refusal: no usage */
	}
	return ends[0] - starts[0] == ends[1] - starts[1] &&
	       memcmp(starts[0], starts[1], (size_t)(ends[0] - starts[0])) == 0;
}

/* Whether the text holds a marker head as the reference spells one (the model holds every spelling to G1). */
/* G1's own reading of a head, independent of the engine's: "<" WS ["/" WS] bar WS "DSML" WS bar WS keyword, or a
 * closing one without its "<" ("/" WS bar ...), each WS a run of at most CHAT_MARKER_SPACE_MAX marker spaces, the
 * words in any case. Each step takes the place after the last one (SIZE_MAX: no head) and gives the place after its
 * own. */
static size_t marker_spaces(const struct text *text, size_t at)
{
	size_t end = at;
	while (end < text->count && text->bytes[end] != '\0' &&
	       strchr(MARKER_SPACE_BYTES, text->bytes[end]) != NULL) {
		end++;
	}
	return at != SIZE_MAX && end - at <= CHAT_MARKER_SPACE_MAX ? end :
								     SIZE_MAX;
}

static size_t marker_word(const struct text *text, size_t at, const char *word)
{
	const size_t length = strlen(word);
	bool is_same = at != SIZE_MAX && text->count - at >= length;
	for (size_t index = 0; is_same && index < length; index++) {
		is_same = tolower((unsigned char)text->bytes[at + index]) ==
			  (unsigned char)word[index];
	}
	return is_same ? at + length : SIZE_MAX;
}

static size_t marker_bar(const struct text *text, size_t at)
{
	const size_t narrow = marker_word(text, at, "|");
	return narrow != SIZE_MAX ? narrow : marker_word(text, at, WIDE_BAR);
}

/* The whole heads of a text, in any spelling: what the client's joined text shows of markers. */
static uint32_t markers_counted(const struct text *text)
{
	static const char *const keywords[] = { "function_calls", "tool_calls",
						"calls", "invoke",
						"parameter" };
	uint32_t markers = 0;
	for (size_t at = 0; at < text->count; at++) {
		const bool is_bare = text->bytes[at] == '/';
		size_t position = text->bytes[at] == '<' || is_bare ?
					  marker_spaces(text, at + 1) :
					  SIZE_MAX;
		const size_t closing =
			is_bare ? SIZE_MAX : marker_word(text, position, "/");
		position = closing != SIZE_MAX ? marker_spaces(text, closing) :
						 position;
		position = marker_spaces(text, marker_bar(text, position));
		position = marker_spaces(text,
					 marker_word(text, position, "dsml"));
		position = marker_spaces(text, marker_bar(text, position));
		size_t end = SIZE_MAX;
		for (size_t index = 0;
		     index < sizeof(keywords) / sizeof(keywords[0]) &&
		     end == SIZE_MAX;
		     index++) {
			end = marker_word(text, position, keywords[index]);
		}
		markers += end != SIZE_MAX ? 1u : 0u;
		at = end != SIZE_MAX ? end - 1u : at;
	}
	return markers;
}

/* Whether Messages takes a whole answer's calls: names of [A-Za-z0-9_-], at most 64 bytes, no namespace, and
 * arguments that are a JSON object with no NaN, no Infinity and no key twice. */
static bool messages_take(const struct text *calls)
{
	static const char name_key[] = "\"name\":\"",
			  arguments_key[] = "\"arguments\":";
	static char scratch_bytes[SCRATCH_CAPACITY];
	bool takes = calls->count == 0 ||
		     strstr(calls->bytes, "\"namespace\"") == NULL;
	for (const char *at = calls->count != 0 ? calls->bytes : NULL;
	     takes && at != NULL;) {
		at = strstr(at, name_key);
		if (at == NULL) {
			break;
		}
		at += strlen(name_key);
		const size_t length = strspn(at, MESSAGES_NAME_BYTES);
		const char *const arguments = strstr(at, arguments_key);
		struct text value = { 0 };
		struct json_value document = { 0 };
		struct json_scratch scratch = { .bytes = scratch_bytes,
						.capacity =
							sizeof(scratch_bytes) };
		if (arguments != NULL) {
			(void)string_unescaped(
				arguments + strlen(arguments_key),
				calls->bytes + calls->count, &value);
		}
		takes = at[length] == '"' && length != 0 &&
			length <= MESSAGES_NAME_MOST && value.bytes != NULL &&
			json_read_document(value.bytes, value.count,
					   &document) == JSON_DOCUMENT_VALID &&
			document.text[document.begin] == '{' &&
			!json_has_unquoted(document, "NI") &&
			!json_has_repeated_key(&scratch, document);
		free(value.bytes);
	}
	return takes;
}

/* Every feeding of a case, every API: one answer each time; with expectations, the model's. */
static void case_checked(const struct calls_case *calls_case, bool every_split)
{
	struct observed whole = { 0 }, other = { 0 };
	context = calls_case->name;
	if (!answered(calls_case, API_CHAT, false, FEED_WHOLE, 0, false,
		      &whole)) {
		expect(false, "the request is read");
		return;
	}
	if (calls_case->has_expectation) {
		expect(texts_equal(&whole.content, &calls_case->content),
		       "the model's content");
		expect(texts_equal(&whole.reasoning, &calls_case->reasoning),
		       "the model's reasoning");
		expect(texts_equal(&whole.calls, &calls_case->calls),
		       "the model's calls");
		expect(strcmp(whole.finish, calls_case->finish) == 0,
		       "the model's finish reason");
		expect(memcmp(whole.repairs, calls_case->repairs,
			      sizeof(whole.repairs)) == 0,
		       "the model's repairs");
		if (memcmp(whole.repairs, calls_case->repairs,
			   sizeof(whole.repairs)) != 0) {
			for (uint32_t kind = 0; kind < CHAT_CALLS_REPAIR_KINDS;
			     kind++) {
				(void)printf(" %u/%u", whole.repairs[kind],
					     calls_case->repairs[kind]);
			}
			(void)printf("\n");
		}
	}
	expect(!whole.is_short, "the answer fits");
	/* G1 on the joined text: every head there is counted stray, unless the block went out as text by design */
	expect(calls_case->is_reference || !calls_case->has_tools ||
		       whole.repairs[CHAT_CALLS_REPAIR_BLOCK_AS_TEXT] != 0 ||
		       whole.repairs[CHAT_CALLS_REPAIR_CUT_AT_LIMIT] != 0 ||
		       markers_counted(&whole.content) +
				       markers_counted(&whole.reasoning) <=
			       whole.repairs[CHAT_CALLS_REPAIR_MARKER_STRAY],
	       "G1: no marker in the text but those a repair explains");
	const size_t length = calls_case->stream.count;
	for (uint32_t api = API_CHAT; api < API_COUNT; api++) {
		for (uint32_t streamed = 0; streamed <= 1; streamed++) {
			struct observed first = { 0 };
			const bool has_first =
				api == API_CHAT && streamed == 0 ?
					answered(calls_case, api, false,
						 FEED_WHOLE, 0, false, &first) :
					answered(calls_case, api, streamed != 0,
						 FEED_WHOLE, 0, false, &first);
			if (!has_first) {
				continue;
			}
			const bool is_taken = api != API_MESSAGES ||
					      messages_take(&whole.calls);
			expect(!is_taken ||
				       first.call_count == whole.call_count,
			       "every API gives the same calls");
			expect(api != API_MESSAGES ||
				       first.is_failed != is_taken,
			       "Messages takes the calls it can, and fails on the others");
			if (api == API_CHAT && streamed != 0) {
				expect(texts_equal(&first.content,
						   &whole.content) &&
					       texts_equal(&first.reasoning,
							   &whole.reasoning) &&
					       texts_equal(&first.calls,
							   &whole.calls) &&
					       strcmp(first.finish,
						      whole.finish) == 0,
				       "a stream's deltas join to the whole answer");
				if (!texts_equal(&first.content,
						 &whole.content) ||
				    !texts_equal(&first.reasoning,
						 &whole.reasoning)) {
					(void)printf(
						"  stream content [%s] reasoning [%s] against [%s] [%s]\n",
						first.content.bytes,
						first.reasoning.bytes,
						whole.content.bytes,
						whole.reasoning.bytes);
				}
			}
			for (uint32_t feeding = FEED_SPLIT;
			     feeding <= FEED_CYCLING; feeding++) {
				const size_t last =
					feeding == FEED_SPLIT ?
						(every_split || api == API_CHAT ?
							 length :
							 1u) :
					feeding == FEED_FIXED ? LARGEST_PIECE :
								1u;
				for (size_t size = 1;
				     size <= last &&
				     size <= (feeding == FEED_SPLIT ? length :
								      size);
				     size++) {
					if (!answered(calls_case, api,
						      streamed != 0, feeding,
						      size,
						      size % FEEDINGS_DEFERRED ==
							      0,
						      &other)) {
						continue;
					}
					const bool same =
						api == API_CHAT ?
							texts_equal(
								&other.content,
								&first.content) &&
								texts_equal(
									&other.reasoning,
									&first.reasoning) &&
								texts_equal(
									&other.calls,
									&first.calls) &&
								strcmp(other.finish,
								       first.finish) ==
									0 &&
								memcmp(other.repairs,
								       first.repairs,
								       sizeof(other.repairs)) ==
									0 :
						streamed == 0 ?
							bodies_equal(
								&other.output,
								&first.output) :
							other.call_count ==
								first.call_count;
					if (!same) {
						(void)printf(
							"  feeding %u size %zu api %u streamed %u\n",
							feeding, size, api,
							streamed);
					}
					expect(same,
					       "G2: every feeding gives the same answer, byte for byte");
					observed_free(&other);
				}
			}
			observed_free(&first);
		}
	}
	observed_free(&whole);
}

