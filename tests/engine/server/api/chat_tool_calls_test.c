static void case_made(struct calls_case *calls_case, const char *name,
		      const char *before, const char *block, bool is_thinking,
		      bool is_reference)
{
	char stream[BODY_CAPACITY];
	const int count = snprintf(stream, sizeof(stream), "%s%s%s",
				   is_thinking ? "plan</think>" : "", before,
				   block);
	*calls_case = (struct calls_case){ .has_tools = true,
					   .is_thinking = is_thinking,
					   .is_reference = is_reference };
	(void)snprintf(calls_case->name, sizeof(calls_case->name), "%s", name);
	text_set(&calls_case->stream, stream, count > 0 ? (size_t)count : 0);
	text_set(&calls_case->tools, DECLARED_TOOLS, sizeof(DECLARED_TOOLS));
}

static void case_free(struct calls_case *calls_case)
{
	struct text *const texts[] = {
		&calls_case->stream,	&calls_case->tools,
		&calls_case->stops,	&calls_case->content,
		&calls_case->reasoning, &calls_case->calls
	};
	for (size_t index = 0; index < sizeof(texts) / sizeof(texts[0]);
	     index++) {
		free(texts[index]->bytes);
		*texts[index] = (struct text){ 0 };
	}
}

/* What a whole Chat answer of a case gives, against what it must. */
static void answer_expected(const struct calls_case *calls_case,
			    const char *content, const char *calls,
			    const char *finish)
{
	struct observed observed = { 0 };
	const int before = failures;
	context = calls_case->name;
	if (answered(calls_case, API_CHAT, false, FEED_WHOLE, 0, false,
		     &observed)) {
		expect(observed.content.count == strlen(content) &&
			       memcmp(observed.content.bytes, content,
				      observed.content.count) == 0,
		       "the content");
		expect(observed.calls.count == strlen(calls) &&
			       memcmp(observed.calls.bytes, calls,
				      observed.calls.count) == 0,
		       "the calls, byte for byte");
		expect(strcmp(observed.finish, finish) == 0,
		       "the finish reason");
		if (failures != before) {
			(void)printf("  content [%s] calls [%s] finish %s\n",
				     observed.content.bytes,
				     observed.calls.bytes, observed.finish);
		}
	} else {
		expect(false, "the request is read");
	}
	observed_free(&observed);
}

/* The calls a case has given out once every byte has come, before its end. */
static uint32_t calls_before_end(const struct calls_case *calls_case)
{
	struct chat_request *const request = calloc(1, sizeof(*request));
	struct chat_answer answer = { 0 };
	struct chat_buffer names = { 0 };
	uint32_t calls = UINT32_MAX;
	if (request != NULL &&
	    request_read(calls_case, API_CHAT, false, request, &names)) {
		chat_answer_begin(&answer, request, MODEL, IDENTIFIER, CREATED,
				  PROMPT_TOKENS);
		answer.tool_names = &names;
		(void)chat_answer_token(&answer, calls_case->stream.bytes,
					(uint32_t)calls_case->stream.count);
		calls = answer.call_count;
		chat_answer_free(&answer);
	}
	chat_buffer_free(&names);
	free(request);
	return calls;
}

/* How many tool_use blocks a whole Messages answer of a case holds. */
static size_t messages_calls(const struct calls_case *calls_case)
{
	static const char tool_use[] = "\"type\":\"tool_use\"";
	struct observed observed = { 0 };
	size_t count = 0;
	if (answered(calls_case, API_MESSAGES, false, FEED_WHOLE, 0, false,
		     &observed)) {
		for (const char *at =
			     observed.output.count != 0 ?
				     strstr(observed.output.bytes, tool_use) :
				     NULL;
		     at != NULL; at = strstr(at + 1, tool_use)) {
			count++;
		}
	}
	observed_free(&observed);
	return count;
}

