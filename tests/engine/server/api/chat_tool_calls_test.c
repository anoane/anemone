/* A line's hexadecimal text after its word, NUL-ended items of a comma-separated list. */
static void hex_read(const char *hex, struct text *text, bool is_list)
{
	static const char terminator[] = "";
	const size_t length = strcspn(hex, "\r\n");
	text_set(text, terminator, 0);
	for (size_t at = 0; length <= CHAT_MOST_OUTPUT_BYTES && at < length;) {
		if (hex[at] == ',' || at + 1 == length) {
			text_appended(text, terminator,
				      hex[at] == ',' ? 1u : 0u);
			at++;
			continue;
		}
		const char digits[] = { hex[at], hex[at + 1], '\0' };
		const char byte =
			(char)(unsigned char)strtoul(digits, NULL, HEX_BASE);
		text_appended(text, &byte, 1);
		at += HEX_DIGITS_PER_BYTE;
	}
	if (is_list && length != 0) {
		text_appended(text, terminator, 1);
	}
}

static uint32_t corpus_checked(const char *path)
{
	FILE *const file = fopen(path, "rb");
	char *line = NULL;
	size_t capacity = 0;
	uint32_t cases = 0;
	struct calls_case calls_case = { 0 };
	expect(file != NULL, "the corpus opens");
	while (file != NULL && getline(&line, &capacity, file) > 0) {
		const char *const value =
			strchr(line, ' ') != NULL ? strchr(line, ' ') + 1 : "";
		if (strncmp(line, "case ", strlen("case ")) == 0) {
			case_free(&calls_case);
			calls_case =
				(struct calls_case){ .has_expectation = true };
			(void)snprintf(calls_case.name, sizeof(calls_case.name),
				       "%.*s", (int)strcspn(value, "\r\n"),
				       value);
		} else if (strncmp(line, "tools ", strlen("tools ")) == 0) {
			calls_case.has_tools = value[0] != '-';
			hex_read(calls_case.has_tools ? value : "",
				 &calls_case.tools, true);
		} else if (strncmp(line, "stops ", strlen("stops ")) == 0) {
			hex_read(value, &calls_case.stops, true);
		} else if (strncmp(line, "thinking ", strlen("thinking ")) ==
			   0) {
			calls_case.is_thinking = value[0] == '1';
		} else if (strncmp(line, "mode ", strlen("mode ")) == 0) {
			calls_case.is_reference =
				strncmp(value, "reference",
					strlen("reference")) == 0;
		} else if (strncmp(line, "finish ", strlen("finish ")) == 0) {
			calls_case.is_limited =
				strncmp(value, "length", strlen("length")) == 0;
		} else if (strncmp(line, "stream ", strlen("stream ")) == 0) {
			hex_read(value, &calls_case.stream, false);
		} else if (strncmp(line, "content ", strlen("content ")) == 0) {
			hex_read(value, &calls_case.content, false);
		} else if (strncmp(line, "reasoning ", strlen("reasoning ")) ==
			   0) {
			hex_read(value, &calls_case.reasoning, false);
		} else if (strncmp(line, "calls ", strlen("calls ")) == 0) {
			hex_read(value, &calls_case.calls, false);
		} else if (strncmp(line, "expect_finish ",
				   strlen("expect_finish ")) == 0) {
			(void)snprintf(calls_case.finish,
				       sizeof(calls_case.finish), "%.*s",
				       (int)strcspn(value, "\r\n"), value);
		} else if (strncmp(line, "repairs ", strlen("repairs ")) == 0) {
			const char *cursor = value;
			for (uint32_t kind = 0; kind < CHAT_CALLS_REPAIR_KINDS;
			     kind++) {
				char *after = NULL;
				calls_case.repairs[kind] = (uint32_t)strtoul(
					cursor, &after, DECIMAL_BASE);
				cursor = after;
			}
		} else if (strncmp(line, "end", strlen("end")) == 0) {
			case_checked(&calls_case,
				     calls_case.stream.count <=
					     EVERY_SPLIT_MOST_BYTES);
			cases++;
		}
	}
	case_free(&calls_case);
	free(line);
	if (file != NULL) {
		(void)fclose(file);
	}
	return cases;
}

/* A closing head without its "<", of each kind and spelling, in an otherwise exact block: the value is the bytes before
 * it and its spelling is counted (the reference searches its PARAMETER_END without the "<" but refuses a value not
 * ended by one). The bytes after the block's closing are never given out: it stops. A corpus case found it: its
 * value took the closing in. */
enum bare_kind { BARE_PARAMETER, BARE_INVOKE, BARE_CALLS };

static void bare_closings_checked(void)
{
	static const char *const kinds[] = { "parameter", "invoke",
					     "calls" }; /* by enum bare_kind */
	static const char *const forms[] = { "/" DSML " ", "/" DSML,
					     "/ " WIDE_BAR " DSML " WIDE_BAR
					     " ",
					     "/|DSML| " };
	static const char found_case[] =
		"Done.\n\n<" DSML " calls>\n<" DSML
		" invoke name=\"read\">\n<" DSML
		" parameter name=\"path\" string=\"true\">src/a./" DSML
		" parameter>\n<" WIDE_BAR "ML" WIDE_BAR
		" parameter name=\"limit\" string=lse\">10</" DSML
		" parameter>\n</" DSML " invoke>\n</" DSML " calls>";
	struct calls_case calls_case = { 0 };
	struct observed observed = { 0 };
	char stream[BODY_CAPACITY], closing[CLOSING_BYTES], name[BODY_CAPACITY];
	for (size_t kind = 0; kind < sizeof(kinds) / sizeof(kinds[0]); kind++) {
		for (size_t form = 0; form < sizeof(forms) / sizeof(forms[0]);
		     form++) {
			(void)snprintf(closing, sizeof(closing), "%s%s>",
				       forms[form], kinds[kind]);
			(void)snprintf(
				stream, sizeof(stream),
				"\n\n<" DSML " calls>\n<" DSML
				" invoke name=\"read\">\n<" DSML
				" parameter name=\"path\" string=\"true\">src/a.c%s\n%s\n%s tail",
				kind == BARE_PARAMETER ? closing :
							 "</" DSML
							 " parameter>",
				kind == BARE_INVOKE ? closing :
						      "</" DSML " invoke>",
				kind == BARE_CALLS ? closing :
						     "</" DSML " calls>");
			(void)snprintf(
				name, sizeof(name),
				"reproduced: a %s closing without its <, form %zu",
				kinds[kind], form);
			case_made(&calls_case, name, "", stream, false, false);
			answer_expected(
				&calls_case, "",
				CALL_OF("read",
					"{\\\"path\\\": \\\"src/a.c\\\"}"),
				"tool_calls");
			expect(answered(&calls_case, API_CHAT, false,
					FEED_WHOLE, 0, false, &observed) &&
				       observed.repairs[CHAT_CALLS_REPAIR_MARKER_SPELLING] ==
					       1u,
			       "its spelling counted");
			observed_free(&observed);
			case_checked(&calls_case, true);
			case_free(&calls_case);
		}
	}
	case_made(
		&calls_case,
		"reproduced: a parameter closing without its <, text after it",
		"", found_case, false, false);
	text_set(&calls_case.stops, "END", sizeof("END"));
	answer_expected(&calls_case,
			"Done.<" WIDE_BAR "ML" WIDE_BAR
			" parameter name=\"limit\" string=lse\">10",
			CALL_OF("read", "{\\\"path\\\": \\\"src/a.\\\"}"),
			"tool_calls");
	expect(answered(&calls_case, API_CHAT, false, FEED_WHOLE, 0, false,
			&observed) &&
		       observed.repairs[CHAT_CALLS_REPAIR_MARKER_SPELLING] ==
			       1 &&
		       observed.repairs[CHAT_CALLS_REPAIR_MARKER_STRAY] == 1 &&
		       observed.repairs[CHAT_CALLS_REPAIR_TEXT_IN_BLOCK] == 1,
	       "the value ends at the closing; the closing, the stray head and the text counted");
	observed_free(&observed);
	case_checked(&calls_case, true);
	case_free(&calls_case);
}

/* Reproduced faults of the tolerant reading, kept with their expected answers. */
static void reproductions_checked(void)
{
	static const char value_cut[] =
		"\n\n<" DSML " calls>\n<" DSML " invoke name=\"bash\">\n<" DSML
		" parameter name=\"command\" string=\"true\">rm -rf ./build/tmp_cache";
	static const char head_cut[] = "\n\n<" DSML " calls>\n<" DSML
				       " invoke name=\"bash\">\n<" DSML
				       " param";
	static const char cut_invoke[] =
		"<" DSML " invoke name=\"bash\">\n<" DSML
		" parameter name=\"command\" string=\"true\">rm -rf ./build/tmp_cache";
	static const char after_call[] = "\n\n<" DSML " calls>\n<" DSML
					 " invoke name=\"read\">\n</" DSML
					 " invoke>\n";
	static const char closing_otherwise[] =
		"\n\n<" DSML " calls>\n<" DSML "invoke name=\"read\">\n</" DSML
		"invoke>\n</" DSML
		"calls>\nI have asked for the file; next I will run the build.\n\n"
		"<|DSML|invoke name=\"bash\"></|DSML|invoke>";
	static const char untrimmed[] = "\n\n<" DSML " calls>\n<" DSML
					" invoke name=\" read\">\n</" DSML
					" invoke>\n</" DSML " calls>";
	static const char done_now[] = "\n\n<" DSML " calls>\n<" DSML
				       " invoke name=\"read\">\n</" DSML
				       " invoke>\nDone now";
	char stream[BODY_CAPACITY], tools[BODY_CAPACITY];
	struct calls_case calls_case = { 0 };
	struct observed observed = { 0 };
	/* At a request limit a value or a head the limit cut gives no call; at the end token the implied
	 * closings still do. */
	for (uint32_t form = 0; form <= 1; form++) {
		const char *const cut = form == 0 ? value_cut : head_cut;
		case_made(&calls_case,
			  form == 0 ? "reproduced: a value cut by the limit" :
				      "reproduced: a head cut by the limit",
			  "", cut, false, false);
		calls_case.is_limited = true;
		answer_expected(&calls_case, cut, "", "length");
		expect(answered(&calls_case, API_CHAT, false, FEED_WHOLE, 0,
				false, &observed) &&
			       observed.repairs[CHAT_CALLS_REPAIR_BLOCK_AS_TEXT] ==
				       1,
		       "no call: the block as text, counted");
		observed_free(&observed);
		case_checked(&calls_case, true);
		case_free(&calls_case);
	}
	case_made(&calls_case, "reproduced: a value cut at the end", "",
		  value_cut, false, false);
	answer_expected(
		&calls_case, "",
		CALL_OF("bash",
			"{\\\"command\\\": \\\"rm -rf ./build/tmp_cache\\\"}"),
		"tool_calls");
	case_checked(&calls_case, true);
	case_free(&calls_case);
	(void)snprintf(stream, sizeof(stream), "%s%s", after_call, cut_invoke);
	case_made(&calls_case,
		  "reproduced: an invoke cut by the limit after a call", "",
		  stream, false, false);
	calls_case.is_limited = true;
	answer_expected(&calls_case, cut_invoke, CALL_OF("read", "{}"),
			"length");
	expect(answered(&calls_case, API_CHAT, false, FEED_WHOLE, 0, false,
			&observed) &&
		       observed.repairs[CHAT_CALLS_REPAIR_CUT_AT_LIMIT] == 1,
	       "the call before it, the cut invoke as text, counted");
	observed_free(&observed);
	case_checked(&calls_case, true);
	case_free(&calls_case);
	/* An exact-opened block's closing spelled otherwise stops generation. */
	case_made(&calls_case,
		  "reproduced: an exact block's closing spelled otherwise", "",
		  closing_otherwise, false, false);
	expect(calls_before_end(&calls_case) == 1,
	       "the closing stops: the call before the end");
	answer_expected(&calls_case, "", CALL_OF("read", "{}"), "tool_calls");
	case_checked(&calls_case, true);
	case_free(&calls_case);
	/* A head the text between tags forms with the content before it is counted stray. */
	case_made(
		&calls_case, "reproduced: a head the joined text forms", "",
		"abc<|DSML|\n<|DSML|invoke name=read></|DSML|invoke>invoke name=bash>",
		false, false);
	answer_expected(&calls_case, "abc<|DSML|invoke name=bash>",
			CALL_OF("read", "{}"), "tool_calls");
	expect(answered(&calls_case, API_CHAT, false, FEED_WHOLE, 0, false,
			&observed) &&
		       observed.repairs[CHAT_CALLS_REPAIR_MARKER_STRAY] == 1,
	       "the joined head counted stray");
	observed_free(&observed);
	case_checked(&calls_case, true);
	case_free(&calls_case);
	/* The reference's reading trims a name too. */
	case_made(&calls_case, "reproduced: an exact block's untrimmed name",
		  "", untrimmed, false, false);
	answer_expected(&calls_case, "", CALL_OF("read", "{}"), "tool_calls");
	case_checked(&calls_case, true);
	case_free(&calls_case);
	/* A declared name too long to keep is skipped alone; the later names still resolve. */
	memset(tools, 'x', LONG_NAME_BYTES);
	(void)snprintf(tools + LONG_NAME_BYTES, sizeof(tools) - LONG_NAME_BYTES,
		       "%c%s", '\0', "job_kill");
	case_made(
		&calls_case,
		"reproduced: a long declared name before the folded one", "",
		"\n\n<|DSML|calls>\n<|DSML|invoke name=JOB-KILL></|DSML|invoke>",
		false, false);
	text_set(&calls_case.tools, tools,
		 LONG_NAME_BYTES + 1u + sizeof("job_kill"));
	answer_expected(&calls_case, "", CALL_OF("job_kill", "{}"),
			"tool_calls");
	expect(answered(&calls_case, API_CHAT, false, FEED_WHOLE, 0, false,
			&observed) &&
		       observed.repairs[CHAT_CALLS_REPAIR_NAME_FOLDED] == 1,
	       "folded to the name after the long one");
	observed_free(&observed);
	case_checked(&calls_case, true);
	case_free(&calls_case);
	/* An unnamed invoke's value is passed over, counted, not lost. */
	case_made(
		&calls_case, "reproduced: an unnamed invoke's value", "",
		"\n<|DSML|invoke>\n<|DSML|parameter name=a>lost value</|DSML|parameter>\n<|DSML|invoke name=read>",
		false, false);
	answer_expected(&calls_case, "", CALL_OF("read", "{}"), "tool_calls");
	expect(answered(&calls_case, API_CHAT, false, FEED_WHOLE, 0, false,
			&observed) &&
		       observed.repairs[CHAT_CALLS_REPAIR_INVOKE_UNNAMED] == 1,
	       "the unnamed invoke counted");
	observed_free(&observed);
	case_checked(&calls_case, true);
	case_free(&calls_case);
	/* Text after an exact block's last invoke, at the end token, is read tolerantly: trimmed. */
	case_made(&calls_case, "reproduced: text after the last exact invoke",
		  "", done_now, false, false);
	answer_expected(&calls_case, "Done now", CALL_OF("read", "{}"),
			"tool_calls");
	case_checked(&calls_case, true);
	case_free(&calls_case);
	bare_closings_checked();
	(void)printf(
		"chat_tool_calls_test: %u reproduced cases, %llu feedings in all\n",
		REPRODUCED_CASES + BARE_CLOSING_CASES,
		(unsigned long long)runs);
}

int main(int argc, char **argv)
{
	if (argc > 1) {
		const uint32_t cases = corpus_checked(argv[1]);
		(void)printf(
			"chat_tool_calls_test: %u corpus cases, %llu feedings, %d failures\n",
			cases, (unsigned long long)runs, failures);
	} else {
		regressions_checked();
		decisions_checked();
		reproductions_checked();
		(void)printf("chat_tool_calls_test: %d failures\n", failures);
	}
	return failures == 0 ? 0 : 1;
}
